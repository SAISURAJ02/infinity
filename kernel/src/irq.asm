[bits 64]

extern irq_handler

global irq0

irq0:
    push qword 0      ; dummy error code, for consistent stack layout
    push qword 32      ; interrupt number (IDT entry 32 = remapped IRQ0/timer)
    jmp irq_common_stub

irq_common_stub:
    push rax
    push rbx
    push rcx
    push rdx
    push rsi
    push rdi
    push rbp
    push r8
    push r9
    push r10
    push r11
    push r12
    push r13
    push r14
    push r15

    mov rdi, rsp
    call irq_handler

    pop r15
    pop r14
    pop r13
    pop r12
    pop r11
    pop r10
    pop r9
    pop r8
    pop rbp
    pop rdi
    pop rsi
    pop rdx
    pop rcx
    pop rbx
    pop rax

    add rsp, 16
    iretq
